"""Guard the committed OpenAPI contract against FastAPI drift.

The checked-in document is the public contract.  This test compares it to the
document generated by the application without requiring a running server or
external services.  Only documentation metadata and the equivalent API prefix
representation are normalized; request and response semantics stay strict.
"""

from __future__ import annotations

from collections.abc import Mapping
from copy import deepcopy
from pathlib import Path
from typing import Any

import yaml
from apps.api.main import create_app

CONTRACT_PATH = (
    Path(__file__).resolve().parents[2]
    / "specs/001-architecture-decision-lab/contracts/api.openapi.yaml"
)
API_PREFIX = "/api/v1"
_DOCUMENTATION_KEYS = frozenset({"description", "examples", "example", "summary", "title"})


def _normalize_openapi(document: Mapping[str, Any]) -> dict[str, Any]:
    """Remove non-contractual documentation metadata from an OpenAPI document.

    ``title``, descriptions, summaries, and examples do not affect the API
    wire contract.  ``servers`` is intentionally excluded because the
    committed document expresses the API prefix there, while FastAPI expresses
    it in generated path keys.
    """
    normalized = dict(_remove_documentation_metadata(deepcopy(dict(document))))
    normalized.pop("servers", None)
    _remove_api_prefix_from_paths(normalized)
    return normalized


def _remove_documentation_metadata(value: Any) -> Any:
    if isinstance(value, dict):
        return {
            key: _remove_documentation_metadata(nested)
            for key, nested in value.items()
            if key not in _DOCUMENTATION_KEYS
        }
    if isinstance(value, list):
        return [_remove_documentation_metadata(item) for item in value]
    return value


def _remove_api_prefix_from_paths(document: dict[str, Any]) -> None:
    paths = document.get("paths")
    if not isinstance(paths, dict):
        return

    document["paths"] = {
        path.removeprefix(API_PREFIX) if path.startswith(f"{API_PREFIX}/") else path: item
        for path, item in paths.items()
    }


def test_committed_openapi_contract_matches_fastapi_document() -> None:
    """Require contract changes to be deliberate and committed with the API."""
    committed = yaml.safe_load(CONTRACT_PATH.read_text(encoding="utf-8"))
    assert isinstance(committed, dict)

    generated = create_app().openapi()

    assert _normalize_openapi(generated) == _normalize_openapi(committed)
